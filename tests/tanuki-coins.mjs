import assert from 'node:assert/strict';
import {coinsTier,calculateAward,redemptionLimit,coinsEnabled,milestoneAmounts,COINS_RULES} from '../src/tanuki-coins.js';
assert.equal(coinsTier(0).percent,2);
assert.equal(coinsTier(999).percent,2);
assert.equal(coinsTier(1000).percent,3);
assert.equal(coinsTier(4999).percent,3);
assert.equal(coinsTier(5000).percent,5);
assert.equal(calculateAward(1000,999,1,milestoneAmounts({})).base,20);
assert.equal(calculateAward(1000,999,1,milestoneAmounts({})).milestone,10);
assert.equal(calculateAward(1000,1000,3,milestoneAmounts({})).milestone,20);
assert.equal(calculateAward(1000,1000,5,milestoneAmounts({})).milestone,40);
assert.equal(calculateAward(1000,5000,10,milestoneAmounts({})).milestone,70);
assert.equal(calculateAward(10000,5000,11,milestoneAmounts({})).base,100);
assert.equal(redemptionLimit(123),24);
assert.equal(redemptionLimit(1000),200);
assert.equal(COINS_RULES.maxBasePerMonth,300);
assert.equal(COINS_RULES.releaseDays,14);
assert.equal(COINS_RULES.validDays,180);
assert.equal(coinsEnabled({ENVIRONMENT:'production',TANUKI_COINS_ENABLED:'true'}),false);
assert.equal(coinsEnabled({ENVIRONMENT:'preview',TANUKI_COINS_ENABLED:'false'}),false);
assert.equal(coinsEnabled({ENVIRONMENT:'preview',TANUKI_COINS_ENABLED:'true'}),true);
assert.deepEqual(milestoneAmounts({TANUKI_COINS_MILESTONES:'5,10,20,40'}),{1:5,3:10,5:20,10:40,configured:true});
assert.throws(()=>redemptionLimit(-1),/Invalid/);
assert.throws(()=>calculateAward(-1,0,1,milestoneAmounts({})),/Invalid/);
console.log('PASS Tanuki Coins rules: tiers, gift milestones, caps, 14-day hold, expiry, Preview-only guard');
